/*
 * kat_gen.c - generates xmss_vectors.h with the XMSS reference
 * implementation (https://github.com/XMSS/xmss-reference, CC0), which
 * implements RFC 8391 with the SP 800-208 parameter sets and PRF_keygen.
 * Built and run by scripts/gen_test_vectors.sh.
 *
 * XMSS cases: seeds (SK_SEED || SK_PRF || PUB_SEED), public key and the
 *   signatures with indices 0..NSIG-1 (deterministic: the device can
 *   regenerate every byte from the seeds).
 * XMSS^MT cases: public key and one signature (verification only: the
 *   reference derives all trees from one seed, SP 800-208 Algorithm 10'
 *   draws a fresh S_XMSS per tree, so only the format is shared).
 *
 * Copyright (c) 2026 The sp800-208-xmss-esp32 authors
 * SPDX-License-Identifier: Apache-2.0
 */

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "params.h"
#include "xmss_core.h"

#define NSIG 3

static void blob(const unsigned char *b, size_t len)
{
  size_t i;
  printf("(const uint8_t *)\"");
  for (i = 0; i < len; i++) {
    printf("\\x%02x", b[i]);
  }
  printf("\", %u", (unsigned)len);
}

static void message(unsigned char *m, size_t len, unsigned salt)
{
  size_t i;
  for (i = 0; i < len; i++) {
    m[i] = (unsigned char)(i * 31 + salt * 7 + 1);
  }
}

int main(void)
{
  static const char *xmss_names[] = {"XMSS-SHA2_10_256", "XMSS-SHA2_10_192",
                                     "XMSS-SHAKE256_10_256", "XMSS-SHAKE256_10_192"};
  static const char *shapes[] = {"20/2", "20/4", "40/4", "40/8", "60/6", "60/12"};
  static const char *hashes[] = {"SHA2", "SHAKE256"};
  static const char *ns[] = {"256", "192"};
  unsigned i, k, c;

  printf("/* Generated by scripts/gen_test_vectors.sh (scripts/kat_gen.c) with the\n");
  printf(" * XMSS reference implementation -- do not edit. */\n");
  printf("#pragma once\n#include <stddef.h>\n#include <stdint.h>\n\n");
  printf("typedef struct {\n  const char *name;\n  int mt;\n  uint32_t oid;\n");
  printf("  const uint8_t *seeds; size_t seedslen; /* SK_SEED || SK_PRF || PUB_SEED, XMSS only */\n");
  printf("  const uint8_t *pk; size_t pklen;\n  const uint8_t *msg; size_t msglen;\n");
  printf("  const uint8_t *sig; size_t siglen;\n} xmss_tv;\n\n");
  printf("static const xmss_tv XMSS_TV[] = {\n");

  for (i = 0; i < sizeof xmss_names / sizeof xmss_names[0]; i++) {
    xmss_params p;
    uint32_t oid;
    unsigned char seed[96], pk[64], *sk, *sm, m[64];
    unsigned long long smlen;
    xmss_str_to_oid(&oid, xmss_names[i]);
    xmss_parse_oid(&p, oid);
    sk = malloc(xmss_xmssmt_core_sk_bytes(&p));
    sm = malloc(p.sig_bytes + sizeof m);
    message(seed, 3 * p.n, 100 + i);
    xmssmt_core_seed_keypair(&p, pk, sk, seed);
    for (k = 0; k < NSIG; k++) {
      unsigned char opk[68];
      size_t mlen = 10 + 17 * k;
      message(m, mlen, k);
      xmssmt_core_sign(&p, sk, sm, &smlen, m, mlen);
      opk[0] = (unsigned char)(oid >> 24);
      opk[1] = (unsigned char)(oid >> 16);
      opk[2] = (unsigned char)(oid >> 8);
      opk[3] = (unsigned char)oid;
      memcpy(opk + 4, pk, 2 * p.n);
      printf("  {\"%s\", 0, 0x%08X, ", xmss_names[i], oid);
      blob(seed, 3 * p.n);
      printf(",\n   ");
      blob(opk, 4 + 2 * p.n);
      printf(", ");
      blob(m, mlen);
      printf(",\n   ");
      blob(sm, p.sig_bytes);
      printf("},\n");
      fprintf(stderr, "%s sig %u\n", xmss_names[i], k);
    }
    free(sk);
    free(sm);
  }

  for (i = 0; i < 2; i++) {
    for (c = 0; c < 2; c++) {
      for (k = 0; k < sizeof shapes / sizeof shapes[0]; k++) {
        char name[48];
        xmss_params p;
        uint32_t oid;
        unsigned char seed[96], pk[64], *sk, *sm, m[64], opk[68];
        unsigned long long smlen;
        const size_t mlen = 33;
        unsigned j;
        snprintf(name, sizeof name, "XMSSMT-%s_%s_%s", hashes[i], shapes[k], ns[c]);
        if (xmssmt_str_to_oid(&oid, name) != 0 || xmssmt_parse_oid(&p, oid) != 0) {
          fprintf(stderr, "unknown %s\n", name);
          return 1;
        }
        sk = malloc(xmss_xmssmt_core_sk_bytes(&p));
        sm = malloc(p.sig_bytes + mlen);
        message(seed, 3 * p.n, 200 + k + 10 * c + 20 * i);
        xmssmt_core_seed_keypair(&p, pk, sk, seed);
        /* advance the index a bit so that the signature uses a nonzero leaf
         * on the lower layers */
        for (j = 0; j < 3; j++) {
          message(m, mlen, j);
          xmssmt_core_sign(&p, sk, sm, &smlen, m, mlen);
        }
        opk[0] = (unsigned char)(oid >> 24);
        opk[1] = (unsigned char)(oid >> 16);
        opk[2] = (unsigned char)(oid >> 8);
        opk[3] = (unsigned char)oid;
        memcpy(opk + 4, pk, 2 * p.n);
        printf("  {\"%s\", 1, 0x%08X, NULL, 0,\n   ", name, oid);
        blob(opk, 4 + 2 * p.n);
        printf(", ");
        blob(m, mlen);
        printf(",\n   ");
        blob(sm, p.sig_bytes);
        printf("},\n");
        fprintf(stderr, "%s\n", name);
        free(sk);
        free(sm);
      }
    }
  }
  printf("};\n\n#define XMSS_TV_COUNT (sizeof XMSS_TV / sizeof XMSS_TV[0])\n");
  return 0;
}
